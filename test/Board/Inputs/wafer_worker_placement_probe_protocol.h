#define WAFER_WP_OUTPUT_SLOT_BASE 4096U
#define WAFER_WP_OUTPUT_SLOT_DATA_BYTES 65536U
#define WAFER_WP_OUTPUT_SLOT_STRIDE                                      \
  (WAFER_WP_OUTPUT_SLOT_DATA_BYTES + 2U * WAFER_WP_GUARD_BYTES)
#define WAFER_WP_RESOURCE_BYTES                                          \
  (WAFER_WP_OUTPUT_SLOT_BASE +                                          \
   WAFER_WP_MAX_ISSUES * WAFER_WP_OUTPUT_SLOT_STRIDE)
#define WAFER_WP_SPM_SLOT_BASE UINT64_C(0x10000)
#define WAFER_WP_SPM_SLOT_STRIDE UINT64_C(0x40000)
#define WAFER_WP_SPM_READ0_OFFSET UINT64_C(0x100)
#define WAFER_WP_SPM_READ1_OFFSET UINT64_C(0x11000)
#define WAFER_WP_SPM_WRITE_OFFSET UINT64_C(0x22000)

_Static_assert(WAFER_WP_RECORD_WORDS * sizeof(uint64_t) <=
                   WAFER_WP_OUTPUT_SLOT_BASE,
               "worker record overlaps archived outputs");
_Static_assert(WAFER_WP_PROGRESS_SENTINEL_SPM_SLOT <
                   WAFER_WP_MAX_ISSUES,
               "progress sentinel SPM slot exceeds owned slots");
_Static_assert(WAFER_WP_SPM_READ0_OFFSET + WAFER_WP_LONG_ISSUE_BYTES <=
                   WAFER_WP_SPM_READ1_OFFSET,
               "worker read operands overlap");
_Static_assert(WAFER_WP_SPM_READ1_OFFSET + WAFER_WP_LONG_ISSUE_BYTES <=
                   WAFER_WP_SPM_WRITE_OFFSET - WAFER_WP_GUARD_BYTES,
               "worker input overlaps the output prefix guard");
_Static_assert(WAFER_WP_SPM_WRITE_OFFSET + WAFER_WP_LONG_ISSUE_BYTES +
                       WAFER_WP_GUARD_BYTES <=
                   WAFER_WP_SPM_SLOT_STRIDE,
               "worker output exceeds its SPM slot");

