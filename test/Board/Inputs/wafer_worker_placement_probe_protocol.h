/*
 * Wire contract for program-local worker placement/progress characterization.
 *
 * The contract intentionally exposes only observations available from the
 * current target: one common device-cycle window, per-worker instruction and
 * blocking counters, raw CONTROL/IB_COUNTER samples, rotating first-observed
 * task-done polling, matching-worker completion, and exact guarded results.
 * First-observed cycles are polling observations, not hardware completion
 * timestamps, and the contract does not name a physical arbiter policy.
 */

