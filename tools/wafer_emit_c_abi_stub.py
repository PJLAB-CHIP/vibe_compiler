#!/usr/bin/env python3
"""Emit a compilable C ABI skeleton from a Wafer package manifest."""

from __future__ import annotations

import argparse
import pathlib
import re
import sys


SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

from wafer_package_manifest import load_manifest, validate_manifest  # noqa: E402


OP_ENUMS = {
    "wafer.abi.rdma": "WAFER_ABI_RDMA",
    "wafer.abi.wdma": "WAFER_ABI_WDMA",
    "wafer.abi.gemm": "WAFER_ABI_GEMM",
    "wafer.abi.elementwise": "WAFER_ABI_ELEMENTWISE",
    "wafer.abi.reduce": "WAFER_ABI_REDUCE",
}

ELEMENTWISE_ENUMS = {
    "add": "WAFER_ELEMENTWISE_ADD",
    "sub": "WAFER_ELEMENTWISE_SUB",
    "mul": "WAFER_ELEMENTWISE_MUL",
    "div": "WAFER_ELEMENTWISE_DIV",
    "max": "WAFER_ELEMENTWISE_MAX",
    "min": "WAFER_ELEMENTWISE_MIN",
    "neg": "WAFER_ELEMENTWISE_NEG",
    "recip": "WAFER_ELEMENTWISE_RECIP",
    "sqrt": "WAFER_ELEMENTWISE_SQRT",
    "rsqrt": "WAFER_ELEMENTWISE_RSQRT",
    "exp": "WAFER_ELEMENTWISE_EXP",
    "tanh": "WAFER_ELEMENTWISE_TANH",
}

REDUCE_ENUMS = {
    "sum": "WAFER_REDUCE_SUM",
    "max": "WAFER_REDUCE_MAX",
    "min": "WAFER_REDUCE_MIN",
}


def c_ident(name: str) -> str:
    ident = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not ident or ident[0].isdigit():
        ident = f"_{ident}"
    return ident


def format_c_float(value: int | float) -> str:
    return format(float(value), ".9g")


def emit_c(manifest: dict) -> str:
    validate_manifest(manifest)
    package_ident = c_ident(manifest["package_name"])
    abi_ops = manifest["abi_ops"]
    workspace_buffers = manifest["workspace_buffers"]
    resident_constants = manifest["resident_constants"]
    placement_ranks = sorted(
        manifest["placement"]["ranks"], key=lambda item: int(item["logical_rank"])
    )

    lines = [
        "/* Generated by wafer_emit_c_abi_stub.py. */",
        "#include <stdint.h>",
        "",
        "typedef enum {",
        "  WAFER_WAIT_ISSUE_ONLY = 0,",
        "} wafer_wait_policy_t;",
        "",
        "typedef enum {",
        "  WAFER_ABI_RDMA = 1,",
        "  WAFER_ABI_WDMA = 2,",
        "  WAFER_ABI_GEMM = 3,",
        "  WAFER_ABI_ELEMENTWISE = 4,",
        "  WAFER_ABI_REDUCE = 5,",
        "} wafer_abi_op_t;",
        "",
        "typedef enum {",
        "  WAFER_ELEMENTWISE_NONE = 0,",
        "  WAFER_ELEMENTWISE_ADD = 1,",
        "  WAFER_ELEMENTWISE_SUB = 2,",
        "  WAFER_ELEMENTWISE_MUL = 3,",
        "  WAFER_ELEMENTWISE_DIV = 4,",
        "  WAFER_ELEMENTWISE_MAX = 5,",
        "  WAFER_ELEMENTWISE_MIN = 6,",
        "  WAFER_ELEMENTWISE_NEG = 7,",
        "  WAFER_ELEMENTWISE_RECIP = 8,",
        "  WAFER_ELEMENTWISE_SQRT = 9,",
        "  WAFER_ELEMENTWISE_RSQRT = 10,",
        "  WAFER_ELEMENTWISE_EXP = 11,",
        "  WAFER_ELEMENTWISE_TANH = 12,",
        "} wafer_elementwise_kind_t;",
        "",
        "typedef enum {",
        "  WAFER_REDUCE_NONE = 0,",
        "  WAFER_REDUCE_SUM = 1,",
        "  WAFER_REDUCE_MAX = 2,",
        "  WAFER_REDUCE_MIN = 3,",
        "} wafer_reduce_kind_t;",
        "",
        "typedef struct {",
        "  wafer_abi_op_t op;",
        "  uint64_t bytes;",
        "  int64_t m;",
        "  int64_t k;",
        "  int64_t n;",
        "  int64_t batch_count;",
        "  wafer_elementwise_kind_t elementwise_kind;",
        "  wafer_reduce_kind_t reduce_kind;",
        "  uint32_t reduce_dimension_count;",
        "  int64_t reduce_dimensions[4];",
        "  double reduce_init_value;",
        "  wafer_wait_policy_t wait_policy;",
        "} wafer_abi_issue_t;",
        "",
        "typedef struct {",
        "  uint32_t logical_rank;",
        "  uint32_t block_id;",
        "  uint32_t card_y;",
        "  uint32_t card_x;",
        "  uint32_t tile_y;",
        "  uint32_t tile_x;",
        "} wafer_tile_launch_arg_t;",
        "",
        "typedef struct {",
        "  uint64_t bytes;",
        "  uint64_t alignment;",
        "} wafer_workspace_buffer_t;",
        "",
        "typedef struct {",
        "  uint64_t bytes;",
        "  uint64_t alignment;",
        "} wafer_resident_constant_t;",
        "",
        f"static const wafer_abi_issue_t k_{package_ident}_issues[] = {{",
    ]

    for op in abi_ops:
        mnemonic = op["op"]
        enum_name = OP_ENUMS[mnemonic]
        bytes_value = int(op.get("bytes", 0))
        m = int(op.get("m", 0))
        k = int(op.get("k", 0))
        n = int(op.get("n", 0))
        default_batch_count = 1 if mnemonic == "wafer.abi.gemm" else 0
        batch_count = int(op.get("batch_count", default_batch_count))
        elementwise_kind = "WAFER_ELEMENTWISE_NONE"
        if mnemonic == "wafer.abi.elementwise":
            elementwise_kind = ELEMENTWISE_ENUMS[op["kind"]]
        reduce_kind = "WAFER_REDUCE_NONE"
        if mnemonic == "wafer.abi.reduce":
            reduce_kind = REDUCE_ENUMS[op["kind"]]
        reduce_dimensions = [int(dim) for dim in op.get("dimensions", [])]
        padded_reduce_dimensions = (reduce_dimensions + [0, 0, 0, 0])[:4]
        reduce_dimensions_text = ", ".join(
            str(dim) for dim in padded_reduce_dimensions
        )
        reduce_init_value = format_c_float(op.get("init_value", 0))
        lines.append(
            f"  {{{enum_name}, {bytes_value}u, {m}, {k}, {n}, {batch_count}, "
            f"{elementwise_kind}, {reduce_kind}, {len(reduce_dimensions)}u, "
            f"{{{reduce_dimensions_text}}}, {reduce_init_value}, "
            "WAFER_WAIT_ISSUE_ONLY},"
        )

    lines.extend(
        [
            "};",
            "",
            f"int {package_ident}_issue_count(void) {{",
            f"  return (int)(sizeof(k_{package_ident}_issues) / "
            f"sizeof(k_{package_ident}_issues[0]));",
            "}",
            "",
            f"static const wafer_tile_launch_arg_t k_{package_ident}_tile_args[] = {{",
        ]
    )

    for rank in placement_ranks:
        coord = rank["physical_coord"]
        lines.append(
            f"  {{{int(rank['logical_rank'])}u, {int(rank['block_id'])}u, "
            f"{int(coord[0])}u, {int(coord[1])}u, {int(coord[2])}u, "
            f"{int(coord[3])}u}},"
        )

    lines.extend(
        [
            "};",
            "",
            f"int {package_ident}_tile_arg_count(void) {{",
            f"  return (int)(sizeof(k_{package_ident}_tile_args) / "
            f"sizeof(k_{package_ident}_tile_args[0]));",
            "}",
            "",
        ]
    )

    lines.append(
        f"static const wafer_workspace_buffer_t "
        f"k_{package_ident}_workspace_buffers[] = {{"
    )
    for buffer in workspace_buffers:
        lines.append(f"  {{{int(buffer['bytes'])}u, {int(buffer['alignment'])}u}},")
    lines.extend(
        [
            "};",
            "",
            f"int {package_ident}_workspace_buffer_count(void) {{",
            f"  return (int)(sizeof(k_{package_ident}_workspace_buffers) / "
            f"sizeof(k_{package_ident}_workspace_buffers[0]));",
            "}",
            "",
            f"static const wafer_resident_constant_t "
            f"k_{package_ident}_resident_constants[] = {{",
        ]
    )
    for constant in resident_constants:
        lines.append(
            f"  {{{int(constant['bytes'])}u, {int(constant['alignment'])}u}},"
        )
    lines.extend(
        [
            "};",
            "",
            f"int {package_ident}_resident_constant_count(void) {{",
            f"  return (int)(sizeof(k_{package_ident}_resident_constants) / "
            f"sizeof(k_{package_ident}_resident_constants[0]));",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True)
    args = parser.parse_args()

    manifest = load_manifest(args.manifest)
    sys.stdout.write(emit_c(manifest))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1)
